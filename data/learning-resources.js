const resolve = (id) => ({ id, ...resourceCatalog[id] });

export function withLearningResources(area) {
  const byTitle = Object.fromEntries(
    (selections[area.slug] || []).map(([title, ...ids]) => [title, ids]),
  );
  return {
    ...area,
    modules: area.modules.map((module) => ({
      ...module,
      resources: (byTitle[module.title] || []).map(resolve),
    })),
    collections: (collections[area.slug] || []).map(resolve),
  };
}
